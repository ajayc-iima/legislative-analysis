"""Build the human-review sheet for flagged-empty reply records.

Every record whose reply text was withheld (unreadable scan, dateless
page, refused mixed Q&A page, quarantine) is listed with the question it
belongs to, the reason, and where the source PDF sits, so a reviewer
can check each one by hand and record a decision. Output:

    data/review/flagged_empty.csv   one row per record
    data/review/FLAGGED_EMPTY.md    same, grouped by reason

Usage: python scripts/build_review_sheet.py
"""

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "packages/analysis/src"))

from legislative_analysis import analysis as base  # noqa: E402

DEFAULT_RUN = Path(r"C:\Users\chou_\AppData\Local\Temp\opencode\extract_run")
REVIEW_DIR = REPO / "data/review"

REASONS = {
    "empty reply text": "unreadable or dateless page - scan yielded no reply text",
    "no PDF on disk": "source PDF missing from data/pdfs",
}


def cell(value):
    """Single-line, pipe-safe cell text for the markdown table."""
    return " ".join(str(value or "").split()).replace("|", "/")


def classify(rec):
    notes = rec.get("needs_review", []) or []
    if any(n.startswith("quarantined:") for n in notes):
        return ("quarantine", "mixed Q&A page quarantined; text withheld "
                              "(data/review/quarantine_list.csv)")
    if any(n.startswith("p") and ":" in n for n in notes):
        return ("technical", "page-level read/OCR error")
    if any("mojibake" in n or "unparseable" in n for n in notes):
        return ("technical", "text layer corrupt or dates unparseable")
    if "empty reply text" in notes:
        return ("refused", REASONS["empty reply text"])
    return ("other", "; ".join(notes) or "no reason recorded")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", default=str(DEFAULT_RUN))
    parser.add_argument("--out-dir", default=str(REVIEW_DIR))
    args = parser.parse_args(argv)

    run_dir = Path(args.run_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    extracted = {}
    for line in (run_dir / "extracted.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            rec = json.loads(line)
            extracted[rec["pdf"]] = rec
    flagged = {p: r for p, r in extracted.items() if not (r.get("reply") or "").strip()}
    if not flagged:
        print("no flagged records")
        return 0

    rows = base.scope_rows(base.load(str(REPO / "data/dl_questions_raw.csv")))
    meta = defaultdict(list)
    for r in rows:
        link = str(r.get("Document_Link") or "").rsplit("/", 1)[-1]
        if link in flagged:
            meta[link].append(r)

    index = {}
    for p in (REPO / "data/pdfs").rglob("*.pdf"):
        index.setdefault(p.name, p)

    fields = ["pdf", "reason_class", "reason", "session", "sitting_date", "question",
              "mla", "department", "subject", "reply_date", "submission_date",
              "needs_review", "pdf_path"]
    out_rows = []
    for name in sorted(flagged):
        rec = flagged[name]
        cls, reason = classify(rec)
        rowinfo = meta.get(name, [{}])[0]
        path = index.get(name)
        out_rows.append({
            "pdf": name,
            "reason_class": cls,
            "reason": reason,
            "session": str(rowinfo.get("Session") or rec.get("session") or ""),
            "sitting_date": str(rowinfo.get("Session_Date") or ""),
            "question": str(rowinfo.get("Question_Number") or rec.get("question") or ""),
            "mla": str(rowinfo.get("Asked_By") or ""),
            "department": str(rowinfo.get("Departments") or ""),
            "subject": str(rowinfo.get("Subject") or ""),
            "reply_date": rec.get("reply_date", ""),
            "submission_date": rec.get("submission_date", ""),
            "needs_review": "; ".join(rec.get("needs_review", [])),
            "pdf_path": (str(path.relative_to(REPO)).replace("\\", "/")
                         if path else "MISSING"),
        })

    csv_path = out_dir / "flagged_empty.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(out_rows)

    grouped = defaultdict(list)
    for r in out_rows:
        grouped[(r["reason_class"], r["reason"])].append(r)
    md = ["# Flagged-empty reply records (human review sheet)", "",
          f"Generated by `scripts/build_review_sheet.py` - {len(out_rows)} records "
          f"of {len(extracted):,} extracted replies hold no reply text. Dates already "
          "recovered by the pipeline are kept; only the text was withheld or could "
          "not be read. Review each PDF, decide, and record the decision here or in "
          "`quarantine_list.csv`.", ""]
    for (cls, reason), rs in sorted(grouped.items()):
        md += [f"## {cls}: {reason} ({len(rs)})", "",
               "| PDF | Session | Question | MLA | Dates recovered | Path |",
               "|---|---|---|---|---|---|"]
        for r in rs:
            dates = ", ".join(d for d in (r["reply_date"], r["submission_date"]) if d) or "—"
            md.append(f"| `{r['pdf']}` | {cell(r['session'])} | "
                      f"{cell(r['question'])} | {cell(r['mla'])} | {dates} | "
                      f"`{r['pdf_path']}` |")
        md.append("")
    (out_dir / "FLAGGED_EMPTY.md").write_text("\n".join(md), encoding="utf-8")

    print(f"review sheet -> {csv_path} + {out_dir / 'FLAGGED_EMPTY.md'} "
          f"({len(out_rows)} records, {len(grouped)} reason classes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())