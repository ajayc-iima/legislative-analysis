"""Port reference tables from the legacy pipeline into reference_data.py.

Uses ast to pull literal assignments out of mgla_data.py, and execs the
enum + registry definitions from mgla_intelligence.py. Nothing is copied
by hand, so the port stays faithful to the legacy source.
"""

import ast
import re
import textwrap
from pathlib import Path

LEGACY = Path(r"D:\ISB\Legislative Preparedness\code")
OUT = Path(r"D:\ISB\legislative-analysis\packages\analysis\src\legislative_analysis\reference_data.py")

LITERAL_NAMES = [
    "DEPT_NORM", "DEPT_HIERARCHY", "MLA_DB", "MLA_CONSTITUENCY",
    "HISTORICAL_MLA_CONSTITUENCY", "CONSTITUENCY_DISTRICT",
    "DISTRICT_REGION", "ABBREVIATIONS", "CONSTITUENCY_ISSUES",
    "MINISTER_SEATS", "RULING_10", "OPPOSITION_10", "RULING_11",
    "OPPOSITION_11", "MACRO_FISCAL", "DEPT_BUDGET",
]

REGEX_NAMES = ["_BOILERPLATE_REPLY_RE", "_CONTRA_POS_RE", "_CONTRA_NEG_RE"]


def literal_tables(path: Path, names: list) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target.id]
        for name in targets:
            if name in names:
                try:
                    found[name] = ast.literal_eval(node.value)
                except ValueError:
                    print(f"  ! {name}: not a pure literal, skipped")
    return found


def registry_source(path: Path, needed_headings: list) -> str:
    """Extract enum classes + registry dicts from the intelligence module."""
    src = path.read_text(encoding="utf-8")
    tree = ast.parse(src)
    chunks = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name.endswith(("SignalType", "EvasionType")):
            chunks.append(ast.get_source_segment(src, node))
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            if isinstance(node, ast.Assign):
                targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            else:
                targets = [node.target.id] if isinstance(node.target, ast.Name) else []
            if any(t in needed_headings for t in targets):
                chunks.append(ast.get_source_segment(src, node))
    return "\n\n".join(c for c in chunks if c)


def regex_source(path: Path, names: list) -> str:
    src = path.read_text(encoding="utf-8")
    tree = ast.parse(src)
    chunks = []
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            if isinstance(node, ast.Assign):
                targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            else:
                targets = [node.target.id] if isinstance(node.target, ast.Name) else []
            if any(t in names for t in targets):
                chunks.append(ast.get_source_segment(src, node))
    return "\n\n".join(c for c in chunks if c)


def main():
    print("Porting literal tables from mgla_data.py ...")
    tables = literal_tables(LEGACY / "mgla_data.py", LITERAL_NAMES)
    for name in LITERAL_NAMES:
        size = len(tables.get(name, {}))
        print(f"  {name}: {'OK' if size else 'MISSING'} ({size} entries)")

    print("Porting signal registries from mgla_intelligence.py ...")
    registry_src = registry_source(
        LEGACY / "mgla_intelligence.py",
        ["SIGNAL_REGISTRY", "QUESTION_SIGNAL_REGISTRY", "EVASION_REGISTRY"],
    )

    print("Porting regexes from mgla_analytics.py ...")
    regex_src = regex_source(LEGACY / "mgla_analytics.py", REGEX_NAMES)

    body = []
    body.append('"""Reference tables ported from the legacy pipeline.\n\n')
    body.append('Generated by scripts/port_reference.py -- do not edit by hand.\n')
    body.append('Sources: mgla_data.py (tables), mgla_intelligence.py (registries),\n')
    body.append('mgla_analytics.py (regexes).\n"""\n')
    body.append("import re\nfrom typing import Dict, List, Tuple\n\n")

    # Literal tables as a single dict, then aliases for readability.
    body.append("TABLES = {\n")
    for name, value in tables.items():
        body.append(f"    {name!r}: {value!r},\n")
    body.append("}\n\n")
    for name in tables:
        body.append(f"{name} = TABLES[{name!r}]\n")
    body.append("\n")

    # Signal registries: exec'd source needs the typing imports it used.
    body.append("from enum import Enum\n\n")
    body.append(registry_src)
    body.append("\n\n")
    body.append(regex_src)
    body.append("\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(body), encoding="utf-8")
    print(f"Wrote {OUT}")

    # Verify it imports.
    import importlib.util
    spec = importlib.util.spec_from_file_location("reference_data", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    print("Import check:")
    print(f"  MLA_DB entries: {len(mod.MLA_DB)}")
    print(f"  CONSTITUENCY_DISTRICT: {len(mod.CONSTITUENCY_DISTRICT)}")
    print(f"  DISTRICT_REGION: {len(mod.DISTRICT_REGION)}")
    print(f"  DEPT_NORM: {len(mod.DEPT_NORM)}")
    print(f"  DEPT_HIERARCHY: {len(mod.DEPT_HIERARCHY)}")
    print(f"  SIGNAL_REGISTRY types: {len(mod.SIGNAL_REGISTRY)}")
    print(f"  EVASION_REGISTRY types: {len(mod.EVASION_REGISTRY)}")
    print(f"  boilerplate regex: {bool(mod._BOILERPLATE_REPLY_RE.pattern)}")


if __name__ == "__main__":
    main()
